#!/usr/bin/env node
/**
 * coc-bridge setup — wires Claude Code's `claude` wrapper to auto-start the bridge
 * and point ANTHROPIC_BASE_URL at localhost:4045
 */
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const { execSync } = require('child_process');

const GREEN  = '\x1b[32m';
const YELLOW = '\x1b[33m';
const RED    = '\x1b[31m';
const RESET  = '\x1b[0m';
const BOLD   = '\x1b[1m';

function ok(msg)   { console.log(`${GREEN}  ✔${RESET}  ${msg}`); }
function warn(msg) { console.log(`${YELLOW}  ⚠${RESET}  ${msg}`); }
function fail(msg) { console.log(`${RED}  ✖${RESET}  ${msg}`); }
function step(msg) { console.log(`\n${BOLD}${msg}${RESET}`); }

// ─────────────────────────────────────────────
// 1. Find the claude binary
// ─────────────────────────────────────────────
step('1. Finding claude binary...');

let claudeBin;
try {
  claudeBin = execSync('which claude', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  ok(`Found: ${claudeBin}`);
} catch (_) {
  fail('claude not found in PATH. Install Claude Code first:');
  console.log('   https://claude.ai/download');
  process.exit(1);
}

// ─────────────────────────────────────────────
// 2. Find the coc-bridge bin (this package)
// ─────────────────────────────────────────────
step('2. Locating coc-bridge...');

let bridgeBin;
try {
  bridgeBin = execSync('which coc-bridge', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  ok(`Found: ${bridgeBin}`);
} catch (_) {
  // Fallback: use the absolute path of this script's package
  bridgeBin = path.resolve(__dirname, '..', 'bin', 'coc-bridge.js');
  warn(`coc-bridge not in PATH, will use: ${bridgeBin}`);
}

// ─────────────────────────────────────────────
// 3. Backup existing claude wrapper if it's already a wrapper
// ─────────────────────────────────────────────
step('3. Wrapping claude binary...');

const claudeBinReal = claudeBin + '-bin';

// Check if claude is already a shell wrapper (not the binary itself)
let alreadyWrapped = false;
try {
  const content = fs.readFileSync(claudeBin, 'utf8');
  if (content.includes('coc-bridge') || content.includes('opencode-claude-bridge')) {
    alreadyWrapped = true;
  }
} catch (_) {}

if (!alreadyWrapped) {
  // Only move the original binary if -bin doesn't already exist
  if (!fs.existsSync(claudeBinReal)) {
    fs.copyFileSync(claudeBin, claudeBinReal);
    fs.chmodSync(claudeBinReal, 0o755);
    ok(`Backed up real binary → ${claudeBinReal}`);
  } else {
    ok(`Backup already exists at ${claudeBinReal}`);
  }

  // Write the wrapper
  const wrapperContent = `#!/usr/bin/env bash
# Generated by coc-bridge setup — do not edit manually
# Re-run: coc-bridge setup

BRIDGE_PORT=\${BRIDGE_PORT:-4045}
BRIDGE_BIN="${bridgeBin}"

# Auto-start coc-bridge if not already running
if ! curl -sf "http://127.0.0.1:\${BRIDGE_PORT}/health" > /dev/null 2>&1; then
  nohup node "\${BRIDGE_BIN}" >> "\${HOME}/.coc-bridge/bridge.log" 2>&1 &
  disown
  # Wait up to 3 seconds for startup
  for i in $(seq 1 60); do
    sleep 0.05
    if curl -sf "http://127.0.0.1:\${BRIDGE_PORT}/health" > /dev/null 2>&1; then break; fi
  done
fi

# Point Claude Code to the bridge
export ANTHROPIC_BASE_URL="http://127.0.0.1:\${BRIDGE_PORT}"
export ANTHROPIC_AUTH_TOKEN="coc-local"
export ANTHROPIC_API_KEY=""

# Model picker labels
export ANTHROPIC_MODEL="\${ANTHROPIC_MODEL:-opencode/space-bunny-free}"
export ANTHROPIC_CUSTOM_MODEL_OPTION_NAME="Space Bunny"
export ANTHROPIC_DEFAULT_OPUS_MODEL="opencode/nemotron-3-ultra-free"
export ANTHROPIC_DEFAULT_OPUS_MODEL_NAME="Nemotron 3 Ultra"
export ANTHROPIC_DEFAULT_SONNET_MODEL="opencode/muse-spark-1.3-contributor-free"
export ANTHROPIC_DEFAULT_SONNET_MODEL_NAME="Muse Spark 1.3"
export ANTHROPIC_DEFAULT_HAIKU_MODEL="opencode/cat-jam-free"
export ANTHROPIC_DEFAULT_HAIKU_MODEL_NAME="Cat Jam"
export ANTHROPIC_DEFAULT_FABLE_MODEL="opencode/ling-3.1-flash-free"
export ANTHROPIC_DEFAULT_FABLE_MODEL_NAME="Ling 3.1 Flash"

export CLAUDE_CODE_DISABLE_UNKNOWN_MODEL_WINDOW_ENFORCEMENT=1
export CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY=1

exec "${claudeBinReal}" "\$@"
`;

  fs.writeFileSync(claudeBin, wrapperContent, { mode: 0o755 });
  ok('Wrapper written to: ' + claudeBin);
} else {
  ok('Wrapper already installed.');
}

// ─────────────────────────────────────────────
// 4. Create log directory
// ─────────────────────────────────────────────
step('4. Creating log directory...');
const logDir = path.join(os.homedir(), '.coc-bridge');
if (!fs.existsSync(logDir)) {
  fs.mkdirSync(logDir, { recursive: true });
  ok(`Created ${logDir}`);
} else {
  ok(`Log dir exists: ${logDir}`);
}

// ─────────────────────────────────────────────
// Done
// ─────────────────────────────────────────────
console.log(`
${GREEN}${BOLD}✅  Setup complete!${RESET}

  Run ${BOLD}claude${RESET} as normal — coc-bridge will auto-start in the background.

  Verify anytime with:
    ${BOLD}coc-bridge doctor${RESET}

  Logs: ${logDir}/bridge.log
`);
