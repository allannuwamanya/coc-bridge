#!/usr/bin/env node
/**
 * coc-bridge setup — wires Claude Code's `claude` wrapper to auto-start the bridge
 * and point ANTHROPIC_BASE_URL at localhost:4045
 */
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const { execSync } = require('child_process');

const GREEN  = '\x1b[32m';
const YELLOW = '\x1b[33m';
const RED    = '\x1b[31m';
const RESET  = '\x1b[0m';
const BOLD   = '\x1b[1m';

function ok(msg)   { console.log(`${GREEN}  ✔${RESET}  ${msg}`); }
function warn(msg) { console.log(`${YELLOW}  ⚠${RESET}  ${msg}`); }
function fail(msg) { console.log(`${RED}  ✖${RESET}  ${msg}`); }
function step(msg) { console.log(`\n${BOLD}${msg}${RESET}`); }

// ─────────────────────────────────────────────
// 1. Find the claude binary
// ─────────────────────────────────────────────
step('1. Finding claude binary...');

let claudeBin;
try {
  claudeBin = execSync('which claude', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  ok(`Found: ${claudeBin}`);
} catch (_) {
  fail('claude not found in PATH. Install Claude Code first:');
  console.log('   https://claude.ai/download');
  process.exit(1);
}

// ─────────────────────────────────────────────
// 2. Find the coc-bridge bin (this package)
// ─────────────────────────────────────────────
step('2. Locating coc-bridge...');

let bridgeBin;
try {
  bridgeBin = execSync('which coc-bridge', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  ok(`Found: ${bridgeBin}`);
} catch (_) {
  // Fallback: use the absolute path of this script's package
  bridgeBin = path.resolve(__dirname, '..', 'bin', 'coc-bridge.js');
  warn(`coc-bridge not in PATH, will use: ${bridgeBin}`);
}

// ─────────────────────────────────────────────
// 3. Backup existing claude wrapper if it's already a wrapper
// ─────────────────────────────────────────────
step('3. Wrapping claude binary...');

const claudeBinReal = claudeBin + '-bin';

// Check if claude is already a shell wrapper (not the binary itself)
let alreadyWrapped = false;
try {
  const content = fs.readFileSync(claudeBin, 'utf8');
  if (content.includes('coc-bridge') || content.includes('opencode-claude-bridge')) {
    alreadyWrapped = true;
  }
} catch (_) {}

if (!alreadyWrapped) {
  // Only move the original binary if -bin doesn't already exist
  if (!fs.existsSync(claudeBinReal)) {
    fs.copyFileSync(claudeBin, claudeBinReal);
    fs.chmodSync(claudeBinReal, 0o755);
    ok(`Backed up real binary → ${claudeBinReal}`);
  } else {
    ok(`Backup already exists at ${claudeBinReal}`);
  }

  // Write the wrapper
  const wrapperContent = `#!/usr/bin/env bash
# Generated by coc-bridge setup — do not edit manually
# Re-run: coc-bridge setup

BRIDGE_PORT=\${BRIDGE_PORT:-4045}
BRIDGE_BIN="${bridgeBin}"

# Auto-start coc-bridge if not already running
if ! curl -sf "http://127.0.0.1:\${BRIDGE_PORT}/health" > /dev/null 2>&1; then
  nohup node "\${BRIDGE_BIN}" >> "\${HOME}/.coc-bridge/bridge.log" 2>&1 &
  disown
  # Wait up to 3 seconds for startup
  for i in $(seq 1 60); do
    sleep 0.05
    if curl -sf "http://127.0.0.1:\${BRIDGE_PORT}/health" > /dev/null 2>&1; then break; fi
  done
fi

# Point Claude Code to the bridge
export ANTHROPIC_BASE_URL="http://127.0.0.1:\${BRIDGE_PORT}"
export ANTHROPIC_AUTH_TOKEN="coc-local"
export ANTHROPIC_API_KEY=""

# Model picker labels
export ANTHROPIC_MODEL="\${ANTHROPIC_MODEL:-opencode/space-bunny-free}"
export ANTHROPIC_CUSTOM_MODEL_OPTION_NAME="Space Bunny"
export ANTHROPIC_DEFAULT_OPUS_MODEL="opencode/nemotron-3-ultra-free"
export ANTHROPIC_DEFAULT_OPUS_MODEL_NAME="Nemotron 3 Ultra"
export ANTHROPIC_DEFAULT_SONNET_MODEL="opencode/muse-spark-1.3-contributor-free"
export ANTHROPIC_DEFAULT_SONNET_MODEL_NAME="Muse Spark 1.3"
export ANTHROPIC_DEFAULT_HAIKU_MODEL="opencode/cat-jam-free"
export ANTHROPIC_DEFAULT_HAIKU_MODEL_NAME="Cat Jam"
export ANTHROPIC_DEFAULT_FABLE_MODEL="opencode/ling-3.1-flash-free"
export ANTHROPIC_DEFAULT_FABLE_MODEL_NAME="Ling 3.1 Flash"

export CLAUDE_CODE_DISABLE_UNKNOWN_MODEL_WINDOW_ENFORCEMENT=1
export CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY=1

exec "${claudeBinReal}" "\$@"
`;

  fs.writeFileSync(claudeBin, wrapperContent, { mode: 0o755 });
  ok('Wrapper written to: ' + claudeBin);
} else {
  ok('Wrapper already installed.');
}

// ─────────────────────────────────────────────
// 4. Create log directory
// ─────────────────────────────────────────────
step('4. Creating log directory...');
const logDir = path.join(os.homedir(), '.coc-bridge');
if (!fs.existsSync(logDir)) {
  fs.mkdirSync(logDir, { recursive: true });
  ok(`Created ${logDir}`);
} else {
  ok(`Log dir exists: ${logDir}`);
}

// ─────────────────────────────────────────────
// 5. Configure VS Code extension automatically
// ─────────────────────────────────────────────
step('5. Configuring VS Code Claude Code extension...');

const vsCodeCandidates = [
  path.join(os.homedir(), '.config', 'Code', 'User', 'settings.json'),
  path.join(os.homedir(), '.var', 'app', 'com.visualstudio.code', 'config', 'Code', 'User', 'settings.json'),
  path.join(os.homedir(), 'Library', 'Application Support', 'Code', 'User', 'settings.json'),
  process.env.APPDATA ? path.join(process.env.APPDATA, 'Code', 'User', 'settings.json') : null
].filter(Boolean);

let vsCodeConfigured = false;
for (const settingsPath of vsCodeCandidates) {
  if (fs.existsSync(settingsPath)) {
    try {
      const raw = fs.readFileSync(settingsPath, 'utf8');
      const stripJsonComments = str => str.replace(/\\"|"(?:\\"|[^"])*"|(\/\/.*|\/\*[\s\S]*?\*\/)/g, (m, g) => g ? '' : m);
      const settings = JSON.parse(stripJsonComments(raw));

      settings['claudeCode.claudeProcessWrapper'] = claudeBin;
      settings['claudeCode.environmentVariables'] = [
        { name: 'ANTHROPIC_BASE_URL', value: 'http://127.0.0.1:4045' },
        { name: 'ANTHROPIC_AUTH_TOKEN', value: 'coc-local' },
        { name: 'ANTHROPIC_API_KEY', value: '' },
        { name: 'CLAUDE_CODE_DISABLE_UNKNOWN_MODEL_WINDOW_ENFORCEMENT', value: '1' },
        { name: 'CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY', value: '1' },
        { name: 'ANTHROPIC_MODEL', value: 'opencode/space-bunny-free' },
        { name: 'ANTHROPIC_CUSTOM_MODEL_OPTION_NAME', value: 'Space Bunny' },
        { name: 'ANTHROPIC_DEFAULT_OPUS_MODEL', value: 'opencode/nemotron-3-ultra-free' },
        { name: 'ANTHROPIC_DEFAULT_OPUS_MODEL_NAME', value: 'Nemotron 3 Ultra' },
        { name: 'ANTHROPIC_DEFAULT_SONNET_MODEL', value: 'opencode/muse-spark-1.3-contributor-free' },
        { name: 'ANTHROPIC_DEFAULT_SONNET_MODEL_NAME', value: 'Muse Spark 1.3' },
        { name: 'ANTHROPIC_DEFAULT_HAIKU_MODEL', value: 'opencode/cat-jam-free' },
        { name: 'ANTHROPIC_DEFAULT_HAIKU_MODEL_NAME', value: 'Cat Jam' },
        { name: 'ANTHROPIC_DEFAULT_FABLE_MODEL', value: 'opencode/ling-3.1-flash-free' },
        { name: 'ANTHROPIC_DEFAULT_FABLE_MODEL_NAME', value: 'Ling 3.1 Flash' }
      ];

      fs.writeFileSync(settingsPath, JSON.stringify(settings, null, 4));
      ok(`Configured VS Code: ${settingsPath}`);
      vsCodeConfigured = true;
    } catch (e) {
      warn(`Could not automatically update ${settingsPath}: ${e.message}`);
    }
  }
}

if (!vsCodeConfigured) {
  warn('VS Code settings not found. If using VS Code, set "claudeCode.claudeProcessWrapper": "' + claudeBin + '"');
}

// ─────────────────────────────────────────────
// 6. Ensure ~/.local/bin symlink exists
// ─────────────────────────────────────────────
step('6. Ensuring CLI command availability...');
try {
  const localBin = path.join(os.homedir(), '.local', 'bin');
  if (!fs.existsSync(localBin)) fs.mkdirSync(localBin, { recursive: true });
  const targetLink = path.join(localBin, 'coc-bridge');
  if (bridgeBin && !fs.existsSync(targetLink)) {
    fs.symlinkSync(bridgeBin, targetLink);
    ok(`Linked coc-bridge to ${targetLink}`);
  }
  // Also ensure opencode-bin is linked if opencode exists in localBin
  const opencodeLink = path.join(localBin, 'opencode');
  const opencodeBinLink = path.join(localBin, 'opencode-bin');
  if (fs.existsSync(opencodeLink) && !fs.existsSync(opencodeBinLink)) {
    try {
      const real = fs.realpathSync(opencodeLink);
      const realBin = path.join(path.dirname(real), 'opencode-bin');
      if (fs.existsSync(realBin)) {
        fs.symlinkSync(realBin, opencodeBinLink);
        ok(`Linked opencode-bin to ${opencodeBinLink}`);
      }
    } catch (_) {}
  }
} catch (_) {}

// ─────────────────────────────────────────────
// Done
// ─────────────────────────────────────────────
console.log(`
${GREEN}${BOLD}✅  Setup complete!${RESET}

  • Terminal: Run ${BOLD}claude${RESET} as normal — coc-bridge auto-starts in background.
  • VS Code : Open the Claude Code extension — models are connected!
  • Switch models: ${BOLD}coc-bridge models${RESET} / ${BOLD}coc-bridge use <id>${RESET}
  • Want normal Claude back? Run: ${BOLD}coc-bridge restore${RESET}

  Logs: ${logDir}/bridge.log
`);
